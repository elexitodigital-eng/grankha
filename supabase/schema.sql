-- ---------------------------------------------------------------- PEDIDOS ---
create table if not exists public.orders (
  id                uuid primary key default gen_random_uuid(),
  reference         text unique not null,             -- GRK-YYMMDD-XXXX
  created_at        timestamptz not null default now(),
  status            text not null default 'pending',  -- pending | paid | fulfilled | cancelled | refunded
  stripe_session_id text,
  stripe_payment_intent text,
  currency          text not null default 'EUR',
  subtotal          numeric(10,2) not null,           -- con IVA incluido
  shipping_price    numeric(10,2) not null default 0,
  vat_included      numeric(10,2) not null default 0,
  total             numeric(10,2) not null,
  donation          numeric(10,2) not null default 0, -- reserva para investigación
  shipping_method   text,
  customer        jsonb not null,
  notes             text,
  raw_payload       jsonb,
  tracking_code     text,
  tracking_url      text,
  tracking_email_sent_at timestamptz,     -- cuándo se avisó al cliente del envío
  supplier_order_id text
);

create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_email_idx on public.orders ((customer->>'email'));
create index if not exists orders_status_idx on public.orders (status);

-- ------------------------------------------------------------ LÍNEAS -------
create table if not exists public.order_items (
  id            bigint generated by default as identity primary key,
  order_id      uuid not null references public.orders(id) on delete cascade,
  sku           text not null,
  slug          text not null,
  name          text not null,
  qty           int  not null check (qty > 0),
  unit_price    numeric(10,2) not null,               -- con IVA incluido
  line_total    numeric(10,2) not null,
  weight_g      int not null default 0,
  supplier_cost numeric(10,2)                         -- coste del proveedor en el momento de la venta
);

create index if not exists order_items_order_idx on public.order_items (order_id);

-- --------------------------------------------------------- SUSCRIPTORES ----
create table if not exists public.subscribers (
  id         bigint generated by default as identity primary key,
  email      text unique not null,
  created_at timestamptz not null default now(),
  source     text default 'web',
  consent    boolean not null default true
);

-- ------------------------------------------------------------ CONTACTOS ----
create table if not exists public.contact_messages (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name       text, email text, order_ref text, message text,
  handled    boolean not null default false
);

-- ------------------------------------------------- SEGURIDAD (RLS) ---------
alter table public.orders            enable row level security;
alter table public.order_items       enable row level security;
alter table public.subscribers       enable row level security;
alter table public.contact_messages  enable row level security;

-- El público solo puede dejar su email en la newsletter.
drop policy if exists "subscribers_insert_public" on public.subscribers;
create policy "subscribers_insert_public"
  on public.subscribers for insert
  to anon with check (true);

-- Los mensajes de contacto se insertan desde la función (service_role).
-- El anónimo NO puede leer pedidos ni contactos:
-- (sin políticas de SELECT para anon => acceso denegado por defecto)

-- ----------------------------------------------------------- VISTA KPIs ----
create or replace view public.v_sales_daily as
select date_trunc('day', created_at)::date as day,
       count(*)                      as orders,
       sum(total)                    as revenue,
       sum(donation)                 as donation_reserved
from public.orders
where status in ('paid','fulfilled')
group by 1
order by 1 desc;

-- ------------------------------------------------------------------ CUPÓN --
-- Reserva mensual destinada a investigación (para el resumen anual)
create or replace view public.v_donation_fund as
select date_trunc('month', created_at)::date as month,
       sum(donation) as reserved
from public.orders
where status in ('paid','fulfilled')
group by 1 order by 1 desc;
